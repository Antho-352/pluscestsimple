		<!-- wp:heading {"level":2,"className":"pcs-section__title"} -->
		<h2 class="wp-block-heading pcs-section__title">Architecture : tout ce qu'on nous demande</h2>
		<!-- /wp:heading -->

		<!-- wp:details {"className":"pcs-faq__item"} -->
		<details class="wp-block-details pcs-faq__item"><summary>Comment savoir si ma maison est en périmètre ABF ?</summary>
			<!-- wp:paragraph -->
			<p>Trois moyens gratuits. Le plus rapide : l'<a href="https://atlas.patrimoines.culture.gouv.fr/">Atlas des Patrimoines</a> du ministère de la Culture, qui localise tous les monuments historiques, Sites Patrimoniaux Remarquables et sites classés. Le <a href="https://www.geoportail-urbanisme.gouv.fr/">Géoportail de l'Urbanisme</a> affiche les servitudes officielles de votre parcelle, dont les périmètres ABF. Enfin, le service urbanisme de votre mairie tranche en quelques minutes. Le périmètre standard est de 500 m autour d'un monument historique (article L. 621-30 du Code du patrimoine), mais il peut être adapté localement par un Périmètre Délimité des Abords (PDA). Si vous êtes concerné, tout travail visible depuis l'extérieur passe par avis de l'ABF.</p>
			<!-- /wp:paragraph -->
		</details>
		<!-- /wp:details -->

		<!-- wp:details {"className":"pcs-faq__item"} -->
		<details class="wp-block-details pcs-faq__item"><summary>Quelle surface d'extension sans permis de construire ?</summary>
			<!-- wp:paragraph -->
			<p>Jusqu'à 40 m² de surface de plancher et d'emprise au sol en zone urbaine (zone U du PLU), une déclaration préalable suffit, à condition que la surface totale après travaux reste inférieure ou égale à 150 m². Hors zone urbaine (zones N, A, AU), le permis devient obligatoire dès 20 m². Au-delà de 40 m², ou dès que le total dépasse 150 m², permis de construire et architecte obligatoires. Vérifiez aussi le coefficient d'emprise au sol (CES) de votre PLU : il peut bloquer un projet bien en deçà des seuils nationaux.</p>
			<!-- /wp:paragraph -->
		</details>
		<!-- /wp:details -->

		<!-- wp:details {"className":"pcs-faq__item"} -->
		<details class="wp-block-details pcs-faq__item"><summary>Mon mur en pisé peut-il être isolé par l'extérieur ?</summary>
			<!-- wp:paragraph -->
			<p>Globalement non, ou alors avec d'extrêmes précautions. Le pisé (terre crue compactée, courant en Auvergne, Lyonnais, Dauphiné, Bresse) fonctionne par migration de vapeur d'eau : il respire. Une isolation par l'extérieur en polystyrène expansé ou en laine de roche enduite ciment bloque cette respiration et provoque humidité piégée, salpêtre, désagrégation lente du mur. Si vous voulez isoler, faites-le par l'intérieur avec des matériaux respirants (chaux-chanvre, terre-paille, panneaux de fibres de bois) en épaisseur modérée (8-12 cm max), avec enduit chaux. Avant tout : diagnostic d'humidité et entretien du pied de mur. Le CAUE et les associations type Maisons Paysannes de France orientent gratuitement.</p>
			<!-- /wp:paragraph -->
		</details>
		<!-- /wp:details -->

		<!-- wp:details {"className":"pcs-faq__item"} -->
		<details class="wp-block-details pcs-faq__item"><summary>Quel est le seuil pour qu'un architecte soit obligatoire ?</summary>
			<!-- wp:paragraph -->
			<p>Surface de plancher totale supérieure à 150 m² après travaux, pour les particuliers (personnes physiques) construisant pour eux-mêmes (article L. 431-3 du Code de l'urbanisme, décret du 5 mai 2017). Si votre maison fait 120 m² et que vous ajoutez 35 m², le total atteint 155 m² : architecte obligatoire pour le permis de construire. Une SCI familiale, un propriétaire bailleur, ou toute société sont tenus de recourir à un architecte quelle que soit la surface. La mission peut être réduite (avant-projet, dépôt de permis uniquement) pour limiter les honoraires.</p>
			<!-- /wp:paragraph -->
		</details>
		<!-- /wp:details -->

		<!-- wp:details {"className":"pcs-faq__item"} -->
		<details class="wp-block-details pcs-faq__item"><summary>Le CAUE, c'est vraiment gratuit ?</summary>
			<!-- wp:paragraph -->
			<p>Oui. Les CAUE sont des associations départementales financées notamment par la taxe d'aménagement, qui mettent à disposition des architectes et paysagistes conseils gratuits pour les particuliers, sans condition de ressources. Vous prenez rendez-vous (souvent par mail, parfois en permanence physique en mairie), apportez plan cadastral, photos, idées de projet. L'architecte conseille sur la faisabilité, les matériaux, l'intégration, l'ABF, le PLU. Il ne fait pas votre projet (pas de conflit d'intérêt) mais valide ou recadre l'approche. Annuaire complet sur <a href="https://www.fncaue.com/">fncaue.com</a>.</p>
			<!-- /wp:paragraph -->
		</details>
		<!-- /wp:details -->

